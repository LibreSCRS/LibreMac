// Golden vectors are computed mechanically from RFC 8949 §4.2 CORE
// DETERMINISTIC ("canonical") CBOR — the same shortest-form-integer /
// definite-length / (length, then bytewise) map-key-order rules
// `CanonicalCBORTests.swift` hand-derives from — by walking the same
// algorithm `CanonicalCBOR.swift.encode()` implements, one field at a time,
// for the exact request/reply/event field lists the LibreDarwin C++ source
// (`Messages.h` / `Messages.cpp`) and the reconciled CDDL
// (`agent/wire/librescrs-agent.cddl`) declare. Field-key byte lengths (and
// so their canonical order) are noted per fixture below.
//
// Two deliberate deviations from a natural first-guess shorthand for these
// fields, resolved in favor of the wire source of truth (documented at
// length on `SignOptions`/`CertificateInfo` in
// `AgentTypes.swift`):
//   - `Sign.opts` has no `tsa` field (CDDL is explicit: the TSA is
//     Config1-owned). The optional fields exercised below are
//     `allowExpired`/`displayName`/`reason`/`location`.
//   - `CertificateInfo` mirrors the wire's grouped `fields` map, not a
//     flat `subjectCN`/`issuerCN`/... shape.

