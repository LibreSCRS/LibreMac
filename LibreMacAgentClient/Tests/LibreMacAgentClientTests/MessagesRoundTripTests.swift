    func signRequestMinimalOptsHasNoExtraKeys() {
        let opts = SignOptions(format: "auto", level: "b-b", packaging: "auto")
        let body = AgentRequest.sign(card: "card/0", cert: "abc123", inFd: 2, opts: opts).encode(req: 8)
